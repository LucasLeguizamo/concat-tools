function toPath(rows: string[]): string {
  let d = "";
  rows.forEach((row, y) => {
    for (const run of row.matchAll(/#+/g)) {
      d += `M${run.index} ${y}h${run[0].length}v1h-${run[0].length}z`;
    }
  });
  return d;
}

const paths = Object.fromEntries(
  Object.entries(bitmaps).map(([name, rows]) => [name, toPath(rows)]),
) as Record<IconName, string>;

export function PixelIcon({ name, size = 32, className }: { name: IconName; size?: number; className?: string }) {
  return (
    <svg
      viewBox="0 0 8 8"
      width={size}
      height={size}
      shapeRendering="crispEdges"
      fill="currentColor"
      aria-hidden="true"
      focusable="false"
      className={className}
    >
      <path d={paths[name]} />
    </svg>
  );
}
